#!/usr/bin/env python3
"""Render the standalone installer from the reviewed consumer and schema modules.

The embedded Python is bootstrap code, not downloaded release code. The Rust
updater embeds the rendered entrypoint at compile time. Preparation checks exact
freshness so installer changes cannot be omitted from the qualified candidate.
"""
from pathlib import Path
import argparse
import base64


def render(root: Path) -> str:
    modules = {}
    for name in ("release_manifest.py", "release_consumer.py"):
        modules[name] = base64.b64encode((root / "scripts" / name).read_bytes()).decode()
    return '''#!/bin/sh
# Generated by scripts/release_installer.py; edit its source modules, not this file.
# Bootstrap trust: this script itself must come from a trusted distribution.
# Payload authority: fully verified signatures only — hosted GitHub attestation
# (gh >= 2.102.0) or the pinned owner key (cosign + GRIPSACK_OWNER_SIGNER_KEY).
# Checksums are never a signature; unsigned bytes are never admitted.
set -eu
command -v python3 >/dev/null 2>&1 || { echo 'gripsack: Python 3.11+ is required' >&2; exit 1; }
exec python3 -I - "$@" <<'GRIPSACK_VERIFIED_INSTALLER'
import base64, pathlib, runpy, sys, tempfile
if sys.version_info < (3, 11):
    raise SystemExit('gripsack: Python 3.11+ is required')
with tempfile.TemporaryDirectory(prefix='gripsack-verifier-') as directory:
    root = pathlib.Path(directory)
    modules = ''' + repr(modules) + '''
    for name, data in modules.items():
        (root / name).write_bytes(base64.b64decode(data, validate=True))
    sys.path.insert(0, str(root))
    runpy.run_path(str(root / 'release_consumer.py'), run_name='__main__')
GRIPSACK_VERIFIED_INSTALLER
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    expected = render(root)
    paths = (root / "install.sh",
             root / "crates/gripsack/src/commands/self_update/installer.sh")
    for installer in paths:
        if args.check:
            if installer.read_text() != expected:
                raise SystemExit(f"{installer} is stale; run python3 scripts/release_installer.py")
        else:
            installer.write_text(expected)


if __name__ == "__main__":
    main()
