// The closure bound includes all expanded tar headers/info/payload. It is
// independent of helper declarations and limits aggregate private spool usage.
const MAX_CLOSURE_BYTES: u64 = 64 * 1024 * 1024 * 1024;
const MAX_CLOSURE_ENTRIES: usize = 1_048_576;

/// Remaining resources for original admission and archive-derived generated
/// files. Sharing passes one instance through its entire realization closure.
pub(crate) struct AdmissionBudget {
    pub bytes: u64,
    pub entries: usize,
}
impl AdmissionBudget {
    pub(crate) fn charge(
        &mut self,
        output: &str,
        bytes: u64,
        entries: usize,
    ) -> Result<(), ExecError> {
        let remaining_bytes = self.bytes.checked_sub(bytes);
        let remaining_entries = self.entries.checked_sub(entries);
        match (remaining_bytes, remaining_entries) {
            (Some(bytes), Some(entries)) => {
                self.bytes = bytes;
                self.entries = entries;
                Ok(())
            }
            _ => Err(failure(
                output,
                "complete closure inventory exceeds acquisition limits (expanded byte/entry bound)",
            )),
        }
    }
}

struct ByteCount(u64, u64);
impl Write for ByteCount {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.0 = self
            .0
            .checked_add(bytes.len() as u64)
            .ok_or_else(|| std::io::Error::other("generated byte count overflow"))?;
        if self.0 > self.1 {
            return Err(std::io::Error::other(
                "generated bytes exceed complete closure byte bound",
            ));
        }
        Ok(bytes.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct SystemRuntime {
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub libraries: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub loaders: Vec<String>,
}
impl SystemRuntime {
    pub(crate) fn is_empty(&self) -> bool {
        self.libraries.is_empty() && self.loaders.is_empty()
    }
}
pub(crate) struct ValidatedTree {
    pub tree: store::hash::PayloadHash,
    pub system: SystemRuntime,
}

/// Publication deliberately strips write bits from regular files (0016 §D3).
/// Callers supply the lifecycle phase; a writable retained file must not gain
/// admission merely because it would have been legal in private staging.
#[derive(Clone, Copy)]
pub(crate) enum FileModes {
    Staged,
    Published,
}
impl FileModes {
    fn expected(self, mode: u32, regular: bool) -> u32 {
        match self {
            Self::Published if regular => mode & !0o222,
            _ => mode,
        }
    }
}
fn failure(output: &str, detail: impl Into<String>) -> ExecError {
    ExecError::Step {
        output: output.into(),
        step: "conda".into(),
        detail: detail.into(),
    }
}

fn compare_file(
    want: &ExpectedFile,
    actual: &mut std::fs::File,
    archive: Option<&CondaArchive>,
    prefix: &str,
    platform: &str,
) -> Result<(), String> {
    let length = actual.metadata().map_err(|error| error.to_string())?.len();
    // Text relocation may grow a file, but never lets a staged length allocate
    // memory. Original payload and comparator are bounded independently.
    if length > MAX_ENTRY_BYTES {
        return Err("staged file exceeds its byte bound".into());
    }
    match &want.content {
        Content::Original {
            path,
            sha256,
            size,
            patch: None,
        } => {
            if length != *size {
                return Err(format!("{path:?} differs from original byte length"));
            }
            let digest =
                super::archive::hash_reader(actual, *size).map_err(|error| error.to_string())?;
            if digest != *sha256 {
                return Err("differs from original archive byte identity".into());
            }
        }
        Content::Original {
            path,
            patch: Some(patch),
            ..
        } => {
            let original = archive
                .ok_or("wheel inventory cannot contain Conda relocation")?
                .payload_bytes(path)
                .map_err(|error| error.to_string())?;
            if patch.placeholder != prefix
                && signing::required(&original, want.mode, patch, platform)
            {
                return Err("relocated Mach-O signing is unsupported on Linux x86_64".into());
            } else {
                super::prefix::verify(
                    &original,
                    actual,
                    &patch.placeholder,
                    prefix,
                    patch.binary,
                    platform,
                )?;
            }
        }
        Content::Generated(expected) => {
            if length != expected.len() as u64 {
                return Err("generated entry point has wrong length".into());
            }
            super::prefix::Comparison(actual)
                .write_all(expected)
                .map_err(|error| error.to_string())?;
        }
        _ => return Err("non-file inventory used for regular file comparison".into()),
    }
    Ok(())
}

fn archive_failure(
    output: &str,
    record: &LockedCondaPackage,
    detail: impl std::fmt::Display,
) -> ExecError {
    failure(
        output,
        format!(
            "package {} version {} build {} URL {} SHA-256 {}: {detail}",
            record.name, record.version, record.build, record.url, record.sha256
        ),
    )
}

/// Admit the exact bytes, using the same bounded parser and lifecycle policy
/// as independent installed-tree validation. No extraction or helper execution.
#[cfg(test)]
pub(super) fn admit_archive(
    output: &str,
    record: &LockedCondaPackage,
    path: &Path,
) -> Result<CondaArchive, ExecError> {
    let archive = CondaArchive::open(path, &record.sha256)
        .map_err(|error| archive_failure(output, record, error))?;
    inventory::admit_scripts(record, &archive)
        .map_err(|error| archive_failure(output, record, error))?;
    Ok(archive)
}

pub(crate) struct AdmittedArchives {
    conda: BTreeMap<String, CondaArchive>,
    wheels: BTreeMap<String, gripsack_conda::wheels::WheelArchive>,
}

/// Keep the private hash-verified spools through materialization so independent
/// validation compares against the admitted bytes without decompressing again.
pub(super) fn admit_archives(
    output: &str,
    locked: &LockedCondaEnvironment,
    archives: &BTreeMap<String, PathBuf>,
) -> Result<AdmittedArchives, ExecError> {
    let mut budget = AdmissionBudget {
        bytes: MAX_CLOSURE_BYTES,
        entries: MAX_CLOSURE_ENTRIES,
    };
    admit_archives_bounded(output, locked, archives, "/gripsack-admission", &mut budget)
}

pub(super) fn admit_archives_bounded(
    output: &str,
    locked: &LockedCondaEnvironment,
    archives: &BTreeMap<String, PathBuf>,
    final_prefix: &str,
    budget: &mut AdmissionBudget,
) -> Result<AdmittedArchives, ExecError> {
    let mut readers = BTreeMap::new();
    let initial_bytes = budget.bytes;
    let initial_entries = budget.entries;
    for record in &locked.packages {
        if !readers.contains_key(&record.sha256) {
            let path = archives
                .get(&record.sha256)
                .ok_or_else(|| archive_failure(output, record, "archive is not retained"))?;
            let reader = CondaArchive::open_bounded(
                path,
                &record.sha256,
                budget.bytes.min(MAX_CLOSURE_BYTES),
                budget.entries.min(MAX_CLOSURE_ENTRIES),
            )
            .map_err(|error| archive_failure(output, record, error))?;
            inventory::admit_scripts(record, &reader)
                .map_err(|error| archive_failure(output, record, error))?;
            budget.charge(output, reader.expanded_bytes, reader.entries)?;
            readers.insert(record.sha256.clone(), reader);
        } else {
            inventory::admit_scripts(record, &readers[&record.sha256])
                .map_err(|error| archive_failure(output, record, error))?;
        }
    }
    let mut wheels = BTreeMap::new();
    for record in &locked.wheels {
        if wheels.contains_key(&record.sha256) {
            return Err(failure(
                output,
                "two wheels claim the same archive identity",
            ));
        }
        let path = archives
            .get(&record.sha256)
            .ok_or_else(|| failure(output, format!("wheel {} is not retained", record.filename)))?;
        let wheel = wheel_validation::admit_bounded(
            locked,
            record,
            path,
            budget.bytes.min(MAX_CLOSURE_BYTES),
            budget.entries.min(MAX_CLOSURE_ENTRIES),
        )
        .map_err(|detail| failure(output, format!("wheel {}: {detail}", record.filename)))?;
        budget.charge(output, wheel.expanded_bytes(), wheel.entry_count())?;
        wheels.insert(record.sha256.clone(), wheel);
    }
    let admitted = AdmittedArchives {
        conda: readers,
        wheels,
    };
    // Installed path ownership is prefix-independent. Prove the complete
    // cross-format graph before any helper can mutate staging.
    let (expected, package_files, wheel_bytes, wheel_entries) =
        expected_inventory(output, locked, &admitted, final_prefix)?;
    budget.charge(output, wheel_bytes, wheel_entries)?;
    for file in expected.values() {
        match &file.content {
            Content::Generated(bytes) => budget.charge(output, bytes.len() as u64, 1)?,
            Content::Original {
                path,
                size,
                patch: Some(patch),
                ..
            } => {
                let original = admitted.conda[&file.archive]
                    .payload_bytes(path)
                    .map_err(|error| failure(output, error.to_string()))?;
                let mut length = ByteCount(0, size.saturating_add(budget.bytes));
                super::prefix::emit(
                    &original,
                    &mut length,
                    &patch.placeholder,
                    final_prefix,
                    patch.binary,
                    &locked.platform,
                )
                .map_err(|detail| failure(output, detail))?;
                budget.charge(output, length.0.saturating_sub(*size), 0)?;
            }
            _ => {}
        }
    }
    for record in &locked.packages {
        let mut length = ByteCount(0, budget.bytes);
        gripsack_conda::receipt::write(
            &mut length,
            record,
            &package_files[record.sha256.as_str()],
            final_prefix,
        )
        .map_err(|error| archive_failure(output, record, error))?;
        budget.charge(output, length.0, 1)?;
    }
    let directories = links::directories(&expected).map_err(|detail| failure(output, detail))?;
    budget.charge(
        output,
        0,
        directories
            .iter()
            .filter(|path| !expected.contains_key(*path))
            .count(),
    )?;
    if initial_bytes - budget.bytes > MAX_CLOSURE_BYTES
        || initial_entries - budget.entries > MAX_CLOSURE_ENTRIES
    {
        return Err(failure(
            output,
            "archive closure exceeds expanded byte/entry bound",
        ));
    }
    Ok(admitted)
}

#[cfg(test)]
pub(crate) fn validate_tree(
    output: &str,
    locked: &LockedCondaEnvironment,
    archives: &BTreeMap<String, PathBuf>,
    tree_root: &Path,
    final_prefix: &str,
    modes: FileModes,
) -> Result<ValidatedTree, ExecError> {
    let readers = admit_archives(output, locked, archives)?;
    validate_admitted_tree(output, locked, &readers, tree_root, final_prefix, modes)
}

pub(super) fn validate_admitted_tree(
    output: &str,
    locked: &LockedCondaEnvironment,
    readers: &AdmittedArchives,
    tree_root: &Path,
    final_prefix: &str,
    modes: FileModes,
) -> Result<ValidatedTree, ExecError> {
    if !matches!(
        locked.platform.as_str(),
        "linux-64" | "linux-aarch64" | "osx-64" | "osx-arm64"
    ) {
        return Err(failure(output, "unsupported Conda installation platform"));
    }
    if !final_prefix.starts_with('/')
        || final_prefix.ends_with('/')
        || final_prefix.len() > super::archive::MAX_PATH_BYTES
        || final_prefix.contains(['\0', '\n', '\r', '\\', '"', '\'', '$', '`'])
        || final_prefix
            .split('/')
            .skip(1)
            .any(|part| matches!(part, "" | "." | ".."))
    {
        return Err(failure(
            output,
            "final prefix is not a canonical shell-safe absolute path",
        ));
    }
    let (expected, package_files, _, _) =
        expected_inventory(output, locked, readers, final_prefix)?;
    let directories = links::directories(&expected).map_err(|detail| failure(output, detail))?;
    let mut conda_directories = BTreeSet::from(["conda-meta".to_owned()]);
    if !locked.wheels.is_empty() {
        for (path, file) in &expected {
            if file.archive.is_empty() {
                continue;
            }
            let mut parent = path.as_str();
            while let Some((ancestor, _)) = parent.rsplit_once('/') {
                conda_directories.insert(ancestor.to_owned());
                parent = ancestor;
            }
        }
    }
    links::verify(&expected, &directories, final_prefix)
        .map_err(|detail| failure(output, detail))?;
    let expected_receipts: BTreeMap<_, _> = locked
        .packages
        .iter()
        .map(|record| {
            (
                format!(
                    "conda-meta/{}-{}-{}.json",
                    record.name, record.version, record.build
                ),
                record,
            )
        })
        .collect();
    let root = gripsack_fs::open(tree_root)?;
    let mut seen = BTreeSet::new();
    let mut receipts = BTreeSet::new();
    let mut sonames_needed = BTreeSet::new();
    let mut loaders = BTreeSet::new();
    let (mut staged_bytes, mut walked) = (0u64, 0usize);
    let entry_cap = expected.len() + directories.len() + expected_receipts.len();
    // Every directory is pinned before walking; leaf reads never follow a
    // final symlink and FIFO/special files cannot block admission.
    let mut stack = vec![(root, String::new())];
    while let Some((directory, parent)) = stack.pop() {
        for entry in directory.entries()? {
            let entry = entry?;
            walked += 1;
            if walked > entry_cap {
                return Err(failure(
                    output,
                    "staged tree exceeds its lock-derived entry bound",
                ));
            }
            let name = entry
                .file_name()
                .into_string()
                .map_err(|_| failure(output, "non-UTF-8 staged path"))?;
            let relative = if parent.is_empty() {
                name.clone()
            } else {
                format!("{parent}/{name}")
            };
            let metadata = directory.symlink_metadata(&name)?;
            if metadata.is_file() {
                if metadata.len() > MAX_CLOSURE_BYTES - staged_bytes {
                    return Err(failure(
                        output,
                        "staged closure exceeds its aggregate byte bound",
                    ));
                }
                staged_bytes += metadata.len();
            }
            if metadata.is_dir() {
                if !directories.contains(&relative) {
                    return Err(failure(
                        output,
                        format!("unaccounted directory {relative:?}"),
                    ));
                }
                if let Some(want) = expected.get(&relative) {
                    if !matches!(want.content, Content::Directory) {
                        return Err(failure(output, format!("{relative:?} has wrong type")));
                    }
                    check_mode(
                        output,
                        &relative,
                        &metadata,
                        modes.expected(want.mode, false),
                    )?;
                    seen.insert(relative.clone());
                } else if !locked.wheels.is_empty() && !conda_directories.contains(&relative) {
                    check_mode(output, &relative, &metadata, 0o755)?;
                }
                stack.push((
                    gripsack_fs::open_dir_nofollow(&directory, Path::new(&name))?,
                    relative,
                ));
                continue;
            }
            if let Some(record) = expected_receipts.get(&relative) {
                let file = gripsack_fs::open_file_nofollow(&directory, Path::new(&name))?;
                let metadata = file.metadata()?;
                check_private_file(output, &relative, &metadata)?;
                check_mode(
                    output,
                    &relative,
                    &metadata,
                    modes.expected(gripsack_conda::receipt::FILE_MODE, true),
                )?;
                gripsack_conda::receipt::verify(
                    file,
                    record,
                    &package_files[record.sha256.as_str()],
                    final_prefix,
                )
                .map_err(|error| failure(output, format!("receipt {relative:?}: {error}")))?;
                receipts.insert(relative);
                continue;
            }
            let want = expected
                .get(&relative)
                .ok_or_else(|| failure(output, format!("unaccounted staged file {relative:?}")))?;
            seen.insert(relative.clone());
            if let Content::Symlink(target) = &want.content {
                if !metadata.file_type().is_symlink()
                    || directory.read_link_contents(&name)?.to_str() != Some(target)
                {
                    return Err(failure(
                        output,
                        format!("symlink {relative:?} differs from original target"),
                    ));
                }
                continue;
            }
            let file = gripsack_fs::open_file_nofollow(&directory, Path::new(&name))?;
            let metadata = file.metadata()?;
            check_private_file(output, &relative, &metadata)?;
            check_mode(
                output,
                &relative,
                &metadata,
                modes.expected(want.mode, true),
            )?;
            let mut file = file.into_std();
            compare_file(
                want,
                &mut file,
                readers.conda.get(&want.archive),
                final_prefix,
                &locked.platform,
            )
            .map_err(|detail| failure(output, format!("{relative:?}: {detail}")))?;
            file.rewind()?;
            let mut head = [0; 4];
            let read = file.read(&mut head)?;
            let elf = read == 4 && &head == b"\x7fELF";
            let macho =
                read == 4 && locked.platform.starts_with("osx-") && signing::is_macho(&head);
            if elf || macho {
                file.rewind()?;
                let runtime = executable::classify(&mut file).map_err(|error| {
                    failure(output, format!("invalid executable {relative:?}: {error}"))
                })?;
                for library in runtime.needed_libraries {
                    let path = Path::new(&library);
                    // Mach relative install names are resolved by native
                    // consumer admission, not misreported as ambient needs.
                    if elf || (path.is_absolute() && !path.starts_with(final_prefix)) {
                        sonames_needed.insert(library.to_string_lossy().into_owned());
                    }
                }
                if let Some(executable::Interpreter::Loader(loader)) = runtime.interpreter {
                    loaders.insert(loader.to_string_lossy().into_owned());
                }
            }
        }
    }
    if !seen.iter().eq(expected.keys()) {
        return Err(failure(
            output,
            "staged tree is missing expected archive/generated paths",
        ));
    }
    if !receipts.iter().eq(expected_receipts.keys()) {
        return Err(failure(
            output,
            "conda-meta receipt set differs from frozen closure",
        ));
    }
    let provided: BTreeSet<_> = expected
        .keys()
        .filter_map(|path| path.rsplit('/').next())
        .collect();
    let system = SystemRuntime {
        libraries: sonames_needed
            .into_iter()
            .filter(|name| !provided.contains(name.as_str()))
            .collect(),
        loaders: loaders.into_iter().collect(),
    };
    Ok(ValidatedTree {
        tree: store::canonical_tree_hash(tree_root)?,
        system,
    })
}

type PackageFiles<'a> = BTreeMap<&'a str, BTreeSet<String>>;

fn expected_inventory<'a>(
    output: &str,
    locked: &'a LockedCondaEnvironment,
    readers: &AdmittedArchives,
    final_prefix: &str,
) -> Result<(BTreeMap<String, ExpectedFile>, PackageFiles<'a>, u64, usize), ExecError> {
    let python = PythonLayout::from_lock(locked).map_err(|detail| failure(output, detail))?;
    let mut expected = BTreeMap::new();
    let mut package_files = BTreeMap::new();
    let mut wheel_bytes = 0u64;
    let mut wheel_entries = 0usize;
    for record in &locked.packages {
        let inventory = inventory::inventory(
            record,
            &readers.conda[&record.sha256],
            python.as_ref(),
            final_prefix,
        )
        .map_err(|detail| archive_failure(output, record, detail))?;
        package_files.insert(record.sha256.as_str(), inventory.keys().cloned().collect());
        merge_inventory(&mut expected, inventory).map_err(|detail| failure(output, detail))?;
    }
    if !locked.wheels.is_empty() {
        let mut metadata = Vec::new();
        let target = gripsack_conda::wheels::PythonTarget::from_lock(locked)
            .map_err(|error| failure(output, error.to_string()))?;
        let site = target
            .site_packages
            .to_str()
            .ok_or_else(|| failure(output, "non-UTF-8 Python site-packages"))?;
        for (installed, file) in &expected {
            let Some(relative) = installed
                .strip_prefix(site)
                .and_then(|rest| rest.strip_prefix('/'))
            else {
                continue;
            };
            let metadata_path = match relative.split_once('/') {
                Some((directory, leaf)) => {
                    (directory.ends_with(".dist-info") && leaf == "METADATA")
                        || (directory.ends_with(".egg-info") && leaf == "PKG-INFO")
                }
                None => relative.ends_with(".egg-info"),
            };
            if !metadata_path || matches!(file.content, Content::Directory) {
                continue;
            }
            let Content::Original {
                path, patch: None, ..
            } = &file.content
            else {
                return Err(failure(
                    output,
                    "Conda Python distribution metadata must be immutable",
                ));
            };
            let bytes = readers.conda[&file.archive]
                .payload_bytes(path)
                .map_err(|error| failure(output, format!("Conda Python metadata: {error}")))?;
            metadata.push((installed.clone(), bytes));
        }
        gripsack_conda::wheels::validate_dependencies(locked, &metadata)
            .map_err(|error| failure(output, format!("wheel dependency closure: {error}")))?;
    }
    for record in &locked.wheels {
        let (inventory, generated_bytes, generated_entries) = wheel_validation::inventory(
            locked,
            record,
            &readers.wheels[&record.sha256],
            final_prefix,
        )
        .map_err(|detail| failure(output, format!("wheel {}: {detail}", record.filename)))?;
        wheel_bytes = wheel_bytes
            .checked_add(generated_bytes)
            .ok_or_else(|| failure(output, "generated wheel byte count overflow"))?;
        wheel_entries = wheel_entries
            .checked_add(generated_entries)
            .ok_or_else(|| failure(output, "generated wheel entry count overflow"))?;
        merge_inventory(&mut expected, inventory).map_err(|detail| failure(output, detail))?;
    }
    for record in &locked.packages {
        let receipt = format!(
            "conda-meta/{}-{}-{}.json",
            record.name, record.version, record.build
        );
        if expected.contains_key(&receipt)
            || expected.keys().any(|path| {
                path.strip_prefix(&receipt)
                    .is_some_and(|rest| rest.starts_with('/'))
            })
        {
            return Err(failure(
                output,
                format!("payload collides with Conda receipt {receipt:?}"),
            ));
        }
    }
    if expected
        .get("conda-meta")
        .is_some_and(|file| !matches!(file.content, Content::Directory))
    {
        return Err(failure(output, "payload occupies the receipt directory"));
    }
    if expected.len() > MAX_CLOSURE_ENTRIES {
        return Err(failure(output, "closure inventory exceeds entry bound"));
    }
    links::directories(&expected).map_err(|detail| failure(output, detail))?;
    Ok((expected, package_files, wheel_bytes, wheel_entries))
}

fn merge_inventory(
    expected: &mut BTreeMap<String, ExpectedFile>,
    inventory: BTreeMap<String, ExpectedFile>,
) -> Result<(), String> {
    for (path, file) in inventory {
        if expected.insert(path.clone(), file).is_some() {
            return Err(format!("path {path:?} is claimed by two packages"));
        }
    }
    Ok(())
}

fn check_mode(
    output: &str,
    path: &str,
    metadata: &gripsack_fs::cap_std::fs::Metadata,
    mode: u32,
) -> Result<(), ExecError> {
    use gripsack_fs::cap_std::fs::PermissionsExt;
    if metadata.permissions().mode() & 0o7777 != mode {
        return Err(failure(
            output,
            format!("{path:?} permissions differ from archive/generated mode"),
        ));
    }
    Ok(())
}
fn check_private_file(
    output: &str,
    path: &str,
    metadata: &gripsack_fs::cap_std::fs::Metadata,
) -> Result<(), ExecError> {
    use gripsack_fs::cap_std::fs::MetadataExt;
    if !metadata.is_file() || metadata.nlink() != 1 {
        return Err(failure(
            output,
            format!("{path:?} is not a private regular file (shared hardlink forbidden)"),
        ));
    }
    Ok(())
}
