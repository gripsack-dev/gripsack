//! Exported env (0001 §3.10, reworked by 0025 §C): deployments contribute
//! variables to the user's shell. The profile lives INSIDE the
//! generation — `generations/<N>/env/profile.sh` — published with the
//! generation before apply's flip; rollback reselects it as published and
//! never writes it (plan/0056 FND-2). It is sourced through
//! `$GRIPSACK_HOME/current/env/profile.sh`. The rc-side path is still
//! stable, but it resolves through the `current` symlink: the profile
//! activates with the generation, indivisibly. (The pre-0.22 stable
//! `env/profile.sh` had two asymmetric windows — new profile before
//! the flip on apply, stale profile after the flip on rollback.)

use gripsack_host::store;
use gripsack_host::store::EnvironmentOperation;
use std::collections::BTreeMap;
use std::io;
use std::path::{Path, PathBuf};

/// The profile's content, pure (0027 §8): generation publication
/// writes it into staging. None when nothing is contributed — the
/// rc-side `[ -f ... ]` guard reads that as "nothing to export".
pub fn render_profile(deployments: &BTreeMap<String, store::DeploymentState>) -> Option<String> {
    render_lines(deployments).map(|lines| lines.join("\n"))
}

/// Where generation `generation` keeps its profile.
pub fn profile_path(home: &Path, generation: store::GenerationId) -> PathBuf {
    home.join("generations")
        .join(generation.to_string())
        .join("env")
        .join("profile.sh")
}

/// Whether a published generation retains the profile its selection
/// activates: one that contributes variables carries
/// `generations/<N>/env/profile.sh`, published with it since 0.22. Read
/// only — a generation is immutable (0027 §8), so rollback refuses a target
/// without its profile instead of writing one into it (plan/0056 FND-2).
pub fn retains_profile(
    home: &Path,
    generation: store::GenerationId,
    deployments: &BTreeMap<String, store::DeploymentState>,
) -> io::Result<bool> {
    if render_profile(deployments).is_none() {
        return Ok(true);
    }
    match std::fs::symlink_metadata(profile_path(home, generation)) {
        Ok(meta) => Ok(meta.is_file()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error),
    }
}

fn render_lines(deployments: &BTreeMap<String, store::DeploymentState>) -> Option<Vec<String>> {
    let mut lines = vec![
        "# Generated by gripsack — regenerated at every activation.".to_string(),
        "# Source this from your shell rc: [ -f \"$XDG_DATA_HOME/gripsack/current/env/profile.sh\" ] && . \"$XDG_DATA_HOME/gripsack/current/env/profile.sh\"".to_string(),
    ];
    // (name, op, resolved value) — first occurrence wins on exact dupes
    let mut seen = std::collections::BTreeSet::new();
    let mut any = false;
    for state in deployments.values() {
        for var in &state.env {
            let name = var.name();
            let operation = var.operation();
            // manifests are disk state: a name that is not a shell
            // identifier would inject into every shell that sources
            // this profile. sema rejects these at eval; this guard is
            // for the hand-edited manifest.
            if !is_identifier(name) {
                // data up, rendering at the edge: lower crates never
                // print — this surfaces in the run log instead
                tracing::warn!(name, "skipping env var with an invalid name");
                continue;
            }
            let (resolved, literal): (std::borrow::Cow<'_, str>, bool) = match var {
                store::EnvironmentContribution::LegacyExpression(value) => (
                    value
                        .value
                        .replace("{store}", &state.store_path.to_string_lossy())
                        .into(),
                    false,
                ),
                store::EnvironmentContribution::Structured(
                    store::StructuredEnvironment::Literal { value, .. },
                ) => (value.as_str().into(), true),
                store::EnvironmentContribution::Structured(
                    store::StructuredEnvironment::StorePath { path, .. },
                ) => (
                    format!("{}/{path}", state.store_path.display()).into(),
                    true,
                ),
            };
            if !seen.insert((name, operation, literal, resolved.clone())) {
                continue;
            }
            any = true;
            let line = if literal {
                match operation {
                    EnvironmentOperation::Set => {
                        format!("export {name}={}", ShellLiteral(&resolved))
                    }
                    EnvironmentOperation::Prepend => format!(
                        "export {name}={}${{{name}:+:}}\"${{{name}-}}\"",
                        ShellLiteral(&resolved)
                    ),
                    EnvironmentOperation::Append => format!(
                        "export {name}=\"${{{name}-}}\"${{{name}:+:}}{}",
                        ShellLiteral(&resolved)
                    ),
                }
            } else {
                // Historical generations retain expression expansion exactly.
                match operation {
                    EnvironmentOperation::Set => {
                        format!("export {name}=\"{}\"", shell_quote(&resolved))
                    }
                    EnvironmentOperation::Prepend => {
                        format!("export {name}=\"{}:${{{name}}}\"", shell_quote(&resolved))
                    }
                    EnvironmentOperation::Append => {
                        format!("export {name}=\"${{{name}}}:{}\"", shell_quote(&resolved))
                    }
                }
            };
            lines.push(line);
        }
    }
    if !any {
        return None;
    }
    Some(lines)
}

/// A shell-safe env var name: POSIX identifier rules. The value side
/// is quoted; the name side cannot be, so it is validated instead.
pub(crate) fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Escape backslash, quote, and backtick (the caller adds the double
/// quotes). `$` is left alone: values like "$HOME/bin" expand at
/// source time — that is a feature (0001 §3.10).
/// `$` stays live BY DESIGN ("$HOME/bin" expands at source time).
/// That deliberately also admits $(...) and ${...} — env values come
/// from the trusted, eval-gated repo, and the profile is documented
/// as sourced code (0030 §19). Backticks are escaped: no gripsack
/// feature needs them, and they're the legacy execution form.
fn shell_quote(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('`', "\\`")
}

/// A shell word that can carry data but cannot grant expansion authority.
pub(crate) struct ShellLiteral<'a>(pub &'a str);
impl std::fmt::Display for ShellLiteral<'_> {
    fn fmt(&self, out: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        out.write_str("'")?;
        let mut parts = self.0.split('\'');
        if let Some(first) = parts.next() {
            out.write_str(first)?;
        }
        for part in parts {
            out.write_str("'\\''")?;
            out.write_str(part)?;
        }
        out.write_str("'")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use gripsack_host::store::Ownership;
    use gripsack_host::store::RetainedEnvironment;

    fn state(store: &str, env: Vec<RetainedEnvironment>) -> store::DeploymentState {
        store::DeploymentState {
            store_path: PathBuf::from(store),
            build_only: false,
            intents: vec![],
            verified: None,
            entries: vec![store::DeployedEntry {
                from: "a".into(),
                to: "~/.a".into(),
                key: None,
                ownership: store::StoredOwnership::Legacy(Ownership::Owned),
                vars: Default::default(),
                hash: gripsack_host::store::hash::ManifestHash::from_raw("h".into()),
                file_mode: None,
                source_executable: None,
                prior: None,
                preserved_drift: false,
            }],
            env: env.into_iter().map(Into::into).collect(),
            tree256: None,
            build_closure: vec![],
        }
    }

    fn var(name: &str, op: EnvironmentOperation, value: &str) -> RetainedEnvironment {
        RetainedEnvironment {
            name: name.into(),
            op,
            value: value.into(),
        }
    }

    #[test]
    fn a_contributing_generation_retains_its_profile_only_when_published() {
        let dir = tempfile::tempdir().unwrap();
        let generation = store::GenerationId::new(1);
        let mut deployments = BTreeMap::new();
        deployments.insert(
            "hx".to_string(),
            state(
                "/gs/store/abc-hx",
                vec![var("A", EnvironmentOperation::Set, "1")],
            ),
        );
        // contributions without the published profile: not retained, and
        // the check writes nothing (FND-2)
        assert!(!retains_profile(dir.path(), generation, &deployments).unwrap());
        assert!(!dir.path().join("generations").exists());
        let path = profile_path(dir.path(), generation);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, render_profile(&deployments).unwrap()).unwrap();
        assert!(retains_profile(dir.path(), generation, &deployments).unwrap());
        // a generation with no contributions needs no profile
        deployments.insert("hx".to_string(), state("/gs/store/abc-hx", vec![]));
        let empty = store::GenerationId::new(2);
        assert!(retains_profile(dir.path(), empty, &deployments).unwrap());
    }

    #[test]
    fn retained_literal_values_do_not_gain_legacy_expansion_authority() {
        use store::{EnvironmentContribution, StructuredEnvironment};
        let temporary = tempfile::tempdir().unwrap();
        let literal = "$HOME ${HOME} {store} $(tripwire) `tripwire` ' \\\nsecond line";
        let mut output = state(
            "/gs/store/profile with $HOME",
            vec![
                var("LEGACY", EnvironmentOperation::Set, "$HOME/bin"),
                var("SAME", EnvironmentOperation::Set, "$HOME"),
            ],
        );
        for (name, op, value) in [
            ("LITERAL", EnvironmentOperation::Set, literal),
            ("SAME", EnvironmentOperation::Set, "$HOME"),
            ("PATH", EnvironmentOperation::Prepend, "/declared"),
        ] {
            output.env.push(EnvironmentContribution::Structured(
                StructuredEnvironment::Literal {
                    name: name.into(),
                    op,
                    value: value.into(),
                },
            ));
        }
        output.env.push(EnvironmentContribution::Structured(
            StructuredEnvironment::StorePath {
                name: "PATH".into(),
                op: EnvironmentOperation::Prepend,
                path: "commands".into(),
            },
        ));
        let encoded = serde_json::to_vec(&output).unwrap();
        let output = serde_json::from_slice::<store::DeploymentState>(&encoded).unwrap();
        let deployments = BTreeMap::from([("profile".into(), output)]);
        let profile = temporary.path().join("profile.sh");
        std::fs::write(&profile, render_profile(&deployments).unwrap()).unwrap();
        let marker = temporary.path().join("unexpected-execution");
        let output = std::process::Command::new("/bin/sh")
            .args(["-c", r#"probe="$2"; tripwire() { : > "$probe"; }; . "$1"; printf '%s\0' "$LEGACY" "$LITERAL" "$SAME" "$PATH""#, "env-probe"])
            .arg(profile).arg(&marker)
            .env_clear().env("HOME","/operator-home").env("PATH","/operator-bin")
            .output().unwrap();
        assert!(output.status.success());
        let expected = [
            "/operator-home/bin",
            literal,
            "$HOME",
            "/gs/store/profile with $HOME/commands:/declared:/operator-bin",
        ]
        .join("\0")
            + "\0";
        assert_eq!(output.stdout, expected.as_bytes());
        assert!(!marker.exists());
    }
}
